"""Build, load and sample the Imagen-style text-to-image cascade.

The architecture comes from a :class:`~rsdiff.config.CascadeConfig`; weights come from an
``ImagenTrainer`` checkpoint such as the released ``rsdiff1.5`` file. Sampling goes through
``ImagenTrainer.sample`` so the EMA weights are used, exactly as in the published evaluation.
"""

from __future__ import annotations

import hashlib
import os
import random
from collections.abc import Callable, Sequence
from dataclasses import asdict
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
import torch
from PIL import Image
from PIL.PngImagePlugin import PngInfo

from rsdiff import __version__
from rsdiff.config import CascadeConfig, RunConfig, UnetArch

if TYPE_CHECKING:
    from imagen_pytorch import Imagen, ImagenTrainer

RELEASE_REPO = "asebaq/rsdiff-sr-cascade-ep650"
RELEASE_REVISION = "0ac4d46c3aac32f4fcfb40831fcaf83d5e520fb0"
RELEASE_FILENAME = "ckpt_sr_ep650_step89050.pt"
RELEASE_SHA256 = "1c7721d5c32bd2fdebd938302435269b9a4f5ddb3691ec8f5226c11d110b09a1"

SYNTHETIC_NOTICE = (
    "Synthetic image generated by RSDiff from a text prompt. "
    "It is not an observation or prediction of any real place."
)

# Callable with the ImagenTrainer.sample keywords we use: texts, cond_scale,
# stop_at_unet_number, return_pil_images. Tests substitute a fake.
Sampler = Callable[..., list[Image.Image]]


def seed_everything(seed: int) -> None:
    """Seed Python, NumPy and torch, matching the seeding used for the release."""
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def sha256_file(path: str | Path, chunk_size: int = 1 << 24) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(chunk_size):
            digest.update(chunk)
    return digest.hexdigest()


def verify_checkpoint(path: str | Path, sha256: str = RELEASE_SHA256) -> None:
    """Raise ``ValueError`` unless the file at ``path`` has the expected SHA-256."""
    actual = sha256_file(path)
    if actual != sha256:
        raise ValueError(f"checksum mismatch for {path}: expected {sha256}, got {actual}")


def download_release(cache_dir: str | Path | None = None) -> Path:
    """Download the released ``rsdiff1.5`` checkpoint (1.9 GB) and verify its digest."""
    from huggingface_hub import hf_hub_download

    path = Path(
        hf_hub_download(
            repo_id=RELEASE_REPO,
            filename=RELEASE_FILENAME,
            revision=RELEASE_REVISION,
            cache_dir=cache_dir,
        )
    )
    verify_checkpoint(path)
    return path


def build_unet(arch: UnetArch):
    """Construct one standalone ``imagen_pytorch.Unet`` stage from ``arch``."""
    from imagen_pytorch import Unet

    kwargs = {k: tuple(v) if isinstance(v, list) else v for k, v in asdict(arch).items()}
    del kwargs["optimizer"], kwargs["params_m"]
    return Unet(**kwargs)


def build_imagen(cascade: CascadeConfig, text_embed_dim: int | None = None) -> Imagen:
    """Construct the (untrained) cascade described by ``cascade``.

    ``text_embed_dim`` skips looking up the text encoder's width on the Hugging Face Hub;
    leave it ``None`` when sampling from text.
    """
    from imagen_pytorch import Imagen

    unets = [build_unet(cascade.base)]
    if cascade.sr is not None:
        unets.append(build_unet(cascade.sr))
    image_sizes = tuple(cascade.image_sizes[: len(unets)])
    return Imagen(
        text_encoder_name=cascade.text_encoder,
        text_embed_dim=text_embed_dim,
        unets=tuple(unets) if len(unets) > 1 else unets[0],
        image_sizes=image_sizes if len(unets) > 1 else image_sizes[0],
        timesteps=cascade.timesteps,
        cond_drop_prob=cascade.cond_drop_prob,
    )


def load_cascade(cfg: RunConfig, checkpoint: str | Path, cpu: bool = False) -> ImagenTrainer:
    """Build the cascade for ``cfg`` and load ``checkpoint`` into an ``ImagenTrainer``.

    Runs on CUDA when available, otherwise on CPU. Apple MPS is not used: imagen-pytorch
    2.1.0 casts to float64 while sampling, which MPS does not support.
    """
    from imagen_pytorch import ImagenTrainer

    cpu = cpu or not torch.cuda.is_available()
    trainer = ImagenTrainer(imagen=build_imagen(cfg.cascade), verbose=False, accelerate_cpu=cpu)
    trainer.load(str(checkpoint))
    return trainer


def _slug(text: str, n: int = 40) -> str:
    s = "".join(ch if ch.isalnum() else "_" for ch in text.strip().lower())
    return "_".join(filter(None, s.split("_")))[:n]


def output_paths(captions: Sequence[str], out_dir: Path) -> list[Path]:
    """PNG path per caption; zero-padded so sorted file order equals caption order."""
    pad = max(2, len(str(len(captions) - 1)))
    return [out_dir / f"{i:0{pad}d}_{_slug(c)}.png" for i, c in enumerate(captions)]


def generate(
    sample: Sampler,
    captions: Sequence[str],
    out_dir: str | Path,
    *,
    cond_scale: float = 5.0,
    batch_size: int = 2,
    stop_at_unet: int | None = None,
    on_batch: Callable[[int, int], None] | None = None,
) -> list[Path]:
    """Sample one image per caption into ``out_dir`` and return the PNG paths.

    Writes ``captions.txt`` (one caption per line, in file order) before sampling. A batch
    whose PNGs all exist is skipped, so an interrupted run resumes where it stopped. Every
    PNG carries the prompt and a synthetic-content notice in its text chunks.
    """
    if not captions:
        raise ValueError("no captions to sample")
    if any(not c.strip() for c in captions):
        raise ValueError("captions must be non-empty")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "captions.txt").write_text("\n".join(captions) + "\n", encoding="utf-8")
    paths = output_paths(captions, out_dir)

    for start in range(0, len(captions), batch_size):
        batch_caps = list(captions[start : start + batch_size])
        batch_paths = paths[start : start + batch_size]
        if all(p.exists() for p in batch_paths):
            continue
        kwargs: dict = {"texts": batch_caps, "cond_scale": cond_scale, "return_pil_images": True}
        if stop_at_unet is not None:
            kwargs["stop_at_unet_number"] = stop_at_unet
        images = sample(**kwargs)
        for path, caption, image in zip(batch_paths, batch_caps, images, strict=True):
            info = PngInfo()
            info.add_text("Software", f"rsdiff {__version__}")
            info.add_text("Description", SYNTHETIC_NOTICE)
            info.add_text("Prompt", caption)
            image.save(path, pnginfo=info)
        if on_batch is not None:
            on_batch(min(start + batch_size, len(captions)), len(captions))
    return paths
